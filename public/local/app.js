function calculateChoiceChance(choice) {
  if (choice.automatic) return 1;
  const power = calculateTagPower(choice.tags || []);
  return clamp(0.38 + power * 0.075 - (choice.difficulty || 2) * 0.055, 0.12, 0.9);
}

function calculateTagPower(tags) {
  if (!tags.length) return 0;
  let total = 0;
  const weights = { profession: 1.15, skill: 1.35, item: 0.7, hobby: 0.55, trait: 0.45, health: 0.3, secret: 0.25, phobia: 0.15, relationship: 0.25 };

  activePlayers().forEach((player) => {
    let playerPower = 0;
    player.characteristics.forEach((characteristic) => {
      const matches = characteristic.tags.filter((tag) => tags.includes(tag)).length;
      if (matches) playerPower += (weights[characteristic.type] || 0.25) * matches;
    });
    const role = getPlayerRole(player);
    if (role) {
      const roleMatches = role.tags.filter((tag) => tags.includes(tag)).length;
      playerPower += roleMatches * (player.roleMastery ? 1.25 : 0.75);
    }
    total += Math.min(playerPower, player.roleMastery ? 3.2 : 2.7);
  });

  (state.game.allies || []).forEach((ally) => {
    const matches = (ally.tags || []).filter((tag) => tags.includes(tag)).length;
    total += matches * 0.8;
  });

  return Math.min(total, 7);
}

function eventChanceLabel(chance) {
  if (chance >= 0.76) return "Високий шанс успіху";
  if (chance >= 0.52) return "Середній шанс успіху";
  if (chance >= 0.32) return "Низький шанс успіху";
  return "Дуже ризиковано";
}


