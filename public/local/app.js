function pickCatastrophe(absurdityLevel) {
  const absurdChance = [0, 0.02, 0.05, 0.14, 0.35][absurdityLevel];
  const absurdOptions = CATASTROPHES.filter((c) => c.absurdity);
  const normalOptions = CATASTROPHES.filter((c) => !c.absurdity);
  return clone(Math.random() < absurdChance ? randomItem(absurdOptions) : randomItem(normalOptions));
}

function generateShelter(capacity) {
  const base = clone(randomItem(SHELTERS));
  base.capacity = capacity;
  base.quirk = randomItem(SHELTER_QUIRKS);
  base.resources = Object.fromEntries(
    Object.entries(base.baseResources).map(([key, value]) => [key, clamp(value + randomInt(-7, 7), 25, 100)]),
  );
  return base;
}

function generatePlayers(names, absurdityLevel, uniqueProfessions, minimizeRepeats) {
  const used = {
    professions: new Set(),
    health: new Set(),
    skills: new Set(),
    traits: new Set(),
    items: new Set(),
    secrets: new Set(),
    hobbies: new Set(),
    phobias: new Set(),
    abilities: new Set(),
  };

  return names.map((name, index) => {
    const mode = chooseMode(absurdityLevel);
    const profession = chooseEntry(
      CONTENT.professions,
      mode,
      uniqueProfessions || minimizeRepeats ? used.professions : new Set(),
    );
    if (uniqueProfessions || minimizeRepeats) used.professions.add(profession.id);

    const ageValue = randomInt(18, 78);
    const sex = chooseEntry(CONTENT.sex, "coherent");
    const childfree = chooseEntry(CONTENT.childfree, "coherent");
    const health = chooseHealthEntry(mode, profession, sex, ageValue, minimizeRepeats ? used.health : new Set());
    const skill = chooseContextualEntry(CONTENT.skills, mode, profession, minimizeRepeats ? used.skills : new Set());
    const trait = chooseContextualEntry(CONTENT.traits, mode, profession, minimizeRepeats ? used.traits : new Set());
    const hobby = chooseContextualEntry(CONTENT.hobbies, mode, profession, minimizeRepeats ? used.hobbies : new Set());
    const phobia = chooseContextualEntry(CONTENT.phobias, mode, profession, minimizeRepeats ? used.phobias : new Set());
    const item = chooseContextualEntry(CONTENT.items, mode, profession, minimizeRepeats ? used.items : new Set());
    const secret = chooseContextualEntry(CONTENT.secrets, mode, profession, minimizeRepeats ? used.secrets : new Set());
    const chosenAbility = chooseEntry(CONTENT.abilities, mode, minimizeRepeats ? used.abilities : new Set());

    if (minimizeRepeats) {
      used.health.add(health.id);
      used.skills.add(skill.id);
      used.traits.add(trait.id);
      used.hobbies.add(hobby.id);
      used.phobias.add(phobia.id);
      used.items.add(item.id);
      used.secrets.add(secret.id);
      used.abilities.add(chosenAbility.id);
    }

    const characteristics = [
      makeCharacteristic("profession", profession),
      makeCharacteristic("age", { name: `${ageValue} років`, description: ageDescription(ageValue), tags: [ageValue < 25 ? "young" : ageValue > 60 ? "old" : "adult"] }),
      makeCharacteristic("sex", sex),
      makeCharacteristic("childfree", childfree),
      makeCharacteristic("hobby", hobby),
      makeCharacteristic("phobia", phobia),
      makeCharacteristic("health", health),
      makeCharacteristic("skill", skill),
      makeCharacteristic("trait", trait),
      makeCharacteristic("item", item),
      makeCharacteristic("secret", secret),
    ];

    return {
      id: `player-${index + 1}-${Date.now()}-${cryptoRandomId()}`,
      name,
      mode,
      characteristics,
      ability: { ...clone(chosenAbility), used: false },
      active: true,
      protected: false,
      bonusVote: 0,
      roleId: null,
      roleMastery: false,
      revealedThisRound: 0,
    };
  });
}

function attachRelationships(players, absurdityLevel) {
  if (players.length < 2) return;
  const shuffled = shuffle([...players]);
  shuffled.forEach((player, index) => {
    const target = shuffled[(index + 1) % shuffled.length];
    const allowed = RELATIONSHIP_TEMPLATES.filter((template) => {
      if (template.absurdity === "absurd") return absurdityLevel >= 2;
      if (template.absurdity === "odd") return absurdityLevel >= 1;
      return true;
    });
    const weights = allowed.map((template) => {
      if (template.absurdity === "absurd") return [0, 0, 0.4, 1.5, 4][absurdityLevel];
      if (template.absurdity === "odd") return [0, 0.4, 1.3, 2.5, 3.5][absurdityLevel];
      return 5;
    });
    const template = weightedPick(allowed, weights);
    player.characteristics.push(makeCharacteristic("relationship", {
      name: template.name(target.name),
      description: template.description(target.name),
      tags: template.tags || ["social"],
    }));
  });
}

function chooseHealthEntry(mode, profession, sex, age, usedIds = new Set()) {
  const canBePregnant = sex.id === "female" && age <= 50;
  const pool = CONTENT.health.filter((item) => item.id !== "pregnant" || canBePregnant);
  return chooseContextualEntry(pool, mode, profession, usedIds);
}

function chooseMode(level) {
  const profile = MODE_PROFILES[level];
  const roll = Math.random();
  let cumulative = 0;
  for (const [mode, chance] of Object.entries(profile)) {
    cumulative += chance;
    if (roll <= cumulative) return mode;
  }
  return "coherent";
}

function chooseEntry(pool, mode, usedIds = new Set()) {
  const available = pool.filter((item) => !usedIds.has(item.id));
  const candidates = available.length ? available : pool;
  const weights = candidates.map((item) => absurdityWeight(item.absurdity, mode) * (item.weight || 1));
  return clone(weightedPick(candidates, weights));
}

function chooseContextualEntry(pool, mode, profession, usedIds = new Set()) {
  const available = pool.filter((item) => !usedIds.has(item.id));
  const candidates = available.length ? available : pool;
  const weights = candidates.map((item) => {
    let weight = absurdityWeight(item.absurdity, mode) * (item.weight || 1);
    const sharedTags = item.tags.filter((tag) => profession.tags.includes(tag)).length;

    if (mode === "coherent") weight *= 1 + sharedTags * 1.4;
    if (mode === "contradictory" && item.tags.includes("contradiction")) weight *= 5;
    if (mode === "eccentric" && item.absurdity === "odd") weight *= 3;
    if (mode === "chaotic" && item.absurdity === "absurd") weight *= 4;

    return weight;
  });

  return clone(weightedPick(candidates, weights));
}

function absurdityWeight(absurdity, mode) {
  const matrix = {
    coherent: { normal: 12, odd: 1.2, absurd: 0.08 },
    contradictory: { normal: 8, odd: 2.5, absurd: 0.3 },
    eccentric: { normal: 3, odd: 9, absurd: 1.5 },
    chaotic: { normal: 1.5, odd: 5, absurd: 10 },
  };
  return matrix[mode][absurdity || "normal"];
}

