function saveRoles(event) {
  event.preventDefault();
  const selections = [...els.rolesAssignments.querySelectorAll("[data-role-player]")].map((select) => ({
    playerId: select.dataset.rolePlayer,
    roleId: select.value || null,
  }));
  const assignedIds = selections.map((item) => item.roleId).filter(Boolean);
  if (new Set(assignedIds).size !== assignedIds.length) {
    toast("Кожну роль можна призначити лише одному гравцеві.");
    return;
  }

  selections.forEach(({ playerId, roleId }) => {
    const player = state.game.players.find((item) => item.id === playerId);
    if (player) player.roleId = roleId;
  });
  const summary = selections.filter((item) => item.roleId).map((item) => {
    const player = state.game.players.find((candidate) => candidate.id === item.playerId);
    const role = SHELTER_ROLES.find((candidate) => candidate.id === item.roleId);
    return `${role.name} — ${player.name}`;
  });
  logGame("role", summary.length ? `Розподілено ролі: ${summary.join("; ")}.` : "Усі окремі ролі скасовано.");
  els.rolesDialog.close();
  renderGame();
  saveGame();
}

function renderDiscussionTimer() {
  if (!els.discussionTimerValue || !state.game) return;
  const remaining = Math.max(0, state.game.discussionRemaining || 0);
  const minutes = Math.floor(remaining / 60);
  const seconds = remaining % 60;
  els.discussionTimerValue.textContent = `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
  els.discussionTimerButton.textContent = state.timerRunning ? "Пауза" : remaining > 0 ? "Запустити" : "Скинути";
  els.discussionTimer.classList.toggle("expired", remaining <= 0 && Boolean(state.game.discussionDuration));
}

function toggleDiscussionTimer() {
  if (!state.game?.discussionDuration || state.game.phase !== "discussion") return;
  if ((state.game.discussionRemaining || 0) <= 0) {
    state.game.discussionRemaining = state.game.discussionDuration;
    renderDiscussionTimer();
    saveGame();
    return;
  }
  if (state.timerRunning) {
    stopDiscussionTimer();
    renderDiscussionTimer();
    saveGame();
    return;
  }
  state.timerRunning = true;
  els.discussionTimerButton.textContent = "Пауза";
  state.timerInterval = window.setInterval(() => {
    state.game.discussionRemaining = Math.max(0, (state.game.discussionRemaining || 0) - 1);
    renderDiscussionTimer();
    if (state.game.discussionRemaining <= 0) {
      stopDiscussionTimer();
      renderDiscussionTimer();
      logGame("system", "Час на обговорення вичерпано.");
      saveGame();
      toast("Час на обговорення вичерпано.");
    }
  }, 1000);
}

function stopDiscussionTimer() {
  if (state.timerInterval) window.clearInterval(state.timerInterval);
  state.timerInterval = null;
  state.timerRunning = false;
}

