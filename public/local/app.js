function collectSurvivorTags(players) {
  const tags = new Set();
  players.forEach((player) => {
    player.characteristics.forEach((characteristic) => characteristic.tags.forEach((tag) => tags.add(tag)));
    const role = getPlayerRole(player);
    if (role) role.tags.forEach((tag) => tags.add(tag));
  });
  (state.game.allies || []).forEach((ally) => (ally.tags || []).forEach((tag) => tags.add(tag)));
  return tags;
}

function applyResourceChanges(changes) {
  const details = [];
  const resources = state.game.shelter.resources;
  Object.entries(changes).forEach(([key, amount]) => {
    if (!(key in resources) || !amount) return;
    const before = resources[key];
    resources[key] = clamp(before + amount, 0, 100);
    const actual = resources[key] - before;
    if (!actual) return;
    const sign = actual > 0 ? "+" : "";
    details.push(`${RESOURCE_LABELS[key]} ${sign}${actual}%`);
  });
  return details;
}

