function submitVote() {
  const targetId = state.voting?.selectedTargetId;
  if (!targetId) return;

  const voterId = state.voting.voterIds[state.voting.currentVoterIndex];
  const voter = state.game.players.find((player) => player.id === voterId);
  const weight = 1 + (voter?.bonusVote || 0);
  state.voting.votes[targetId] = (state.voting.votes[targetId] || 0) + weight;
  if (voter) voter.bonusVote = 0;
  state.voting.currentVoterIndex += 1;

  if (state.voting.currentVoterIndex < state.voting.voterIds.length) {
    renderVotingStep();
    return;
  }

  finishVoting();
}

function finishVoting() {
  const votes = state.voting.votes;
  const sorted = Object.entries(votes).sort((a, b) => b[1] - a[1]);
  const maxVotes = sorted[0]?.[1] || 0;
  const tied = sorted.filter(([, count]) => count === maxVotes).map(([id]) => id);
  const eliminatedId = randomItem(tied);
  const eliminated = state.game.players.find((p) => p.id === eliminatedId);

  let resultText;
  if (eliminated?.protected) {
    eliminated.protected = false;
    resultText = `${eliminated.name} мав захист і залишається у грі. Голосування не призвело до вигнання.`;
  } else if (eliminated) {
    eliminated.active = false;
    eliminated.roleId = null;
    resultText = `${eliminated.name} залишає групу. Двері сховища зачиняються ще не назавжди.`;
  } else {
    resultText = "Голосування завершилося без результату.";
  }

  state.game.votesHistory.push({ round: state.game.round, votes: clone(votes), eliminatedId: eliminated?.protected ? null : eliminatedId });
  logGame("vote", resultText);
  state.game.phase = "round_end";
  state.voting = null;
  state.characterVisible = false;

  els.votingDialog.close();
  els.resultTitle.textContent = eliminated?.protected ? "Вигнання скасовано" : eliminated ? `${eliminated.name} вибуває` : "Немає рішення";
  els.resultDescription.textContent = resultText;

  const max = Math.max(...Object.values(votes), 1);
  els.voteResults.innerHTML = activeAndEliminatedPlayersFromVotes(votes).map((player) => {
    const count = votes[player.id] || 0;
    return `<div class="vote-result-row"><span>${escapeHtml(player.name)}</span><div class="vote-bar"><span style="width:${(count / max) * 100}%"></span></div><strong>${count}</strong></div>`;
  }).join("");

  renderGame();
  saveGame();
  els.resultDialog.showModal();
}

function showFinal() {
  const selected = activePlayers();
  const overflow = Math.max(0, selected.length - state.game.capacity);
  const relevantTags = collectSurvivorTags(selected);
  const needs = state.game.catastrophe.needs;
  const coverage = needs.filter((need) => relevantTags.has(need)).length;
  const resources = state.game.shelter.resources;
  const resourceValues = Object.values(resources);
  const resourceAverage = resourceValues.reduce((sum, value) => sum + value, 0) / resourceValues.length;
  const criticalResources = Object.entries(resources).filter(([, value]) => value <= 22);
  const collapsedResources = Object.entries(resources).filter(([, value]) => value <= 0);
  const allies = state.game.allies || [];

  const positiveModifiers = new Set(["technical", "food", "water", "survival", "communication", "rescued_survivor", "found_supplies", "hidden_room", "energy", "scouting", "justice", "cat"]);
  const negativeModifiers = new Set(["air_leak", "mold", "infection", "raiders", "tracked_signal", "contaminated_water", "generator_damage", "fire", "conflict", "unknown_entity", "damaged_airlock", "damaged_heater"]);
  const modifierScore = state.game.finalModifiers.reduce((score, modifier) => {
    if (positiveModifiers.has(modifier)) return score + 1;
    if (negativeModifiers.has(modifier)) return score - 1;
    return score;
  }, 0);

  let score = coverage * 2;
  score += Math.min(selected.length, state.game.capacity);
  score += Math.round(resourceAverage / 18);
  score += Math.min(allies.length, 3);
  score += modifierScore;
  score -= overflow * 2;
  score -= criticalResources.length * 2;
  score -= collapsedResources.length * 4;

  const chronicle = [];
  const survivorNames = selected.map((player) => player.name);
  const allyNames = allies.map((ally) => ally.name);
  chronicle.push({
    time: "День 1",
    text: `Двері остаточно зачинилися. Усередині залишилися: ${survivorNames.join(", ") || "ніхто"}${allyNames.length ? `. Разом із ними — ${allyNames.join(", ")}` : ""}.`,
  });

  if (overflow > 0) {
    chronicle.push({ time: "День 2", text: `Усередині на ${overflow} ${pluralize(overflow, "людину", "людини", "людей")} більше, ніж дозволяє штатна місткість. Спальні місця, повітря та пайки стали причиною постійних суперечок.` });
  }

  const resourceSummary = Object.entries(resources)
    .map(([key, value]) => `${RESOURCE_LABELS[key].toLowerCase()} — ${value}%`)
    .join(", ");
  chronicle.push({ time: "Тиждень 2", text: `Після всіх рішень і аварій стан сховища був таким: ${resourceSummary}.` });

  if (criticalResources.length) {
    chronicle.push({
      time: "Місяць 1",
      text: `Критично виснажені системи: ${criticalResources.map(([key]) => RESOURCE_LABELS[key].toLowerCase()).join(", ")}. Група мусила перейти до надзвичайного режиму економії.`,
    });
  } else {
    chronicle.push({ time: "Місяць 1", text: "Жодна з основних систем не перебувала у критичному стані. Це дало групі час організувати чергування та ремонт." });
  }

  if (coverage === needs.length) {
    chronicle.push({ time: "Місяць 2", text: "Серед мешканців знайшлися компетенції для протидії всім ключовим загрозам катастрофи. Перші серйозні випробування вдалося пройти без незворотних втрат." });
  } else {
    const missing = needs.filter((need) => !relevantTags.has(need));
    chronicle.push({ time: "Місяць 2", text: `Групі бракувало компетенцій у сферах: ${missing.map(tagToUkrainian).join(", ")}. Кожна аварія в цих галузях забирала більше часу й ресурсів.` });
  }

  if (allies.length) {
    chronicle.push({
      time: "Місяць 4",
      text: `Рішення під час криз принесли не лише втрати. ${allies.map((ally) => `${ally.name} — ${ally.description.toLowerCase()}`).join("; ")}.`,
    });
  }

  const assignedRoles = selected.filter((player) => getPlayerRole(player));
  if (assignedRoles.length) {
    chronicle.push({
      time: "Місяць 4",
      text: `Роботу вдалося впорядкувати завдяки розподілу обов’язків: ${assignedRoles.map((player) => `${getPlayerRole(player).name.toLowerCase()} — ${player.name}`).join("; ")}.`,
    });
    score += Math.min(2, Math.floor(assignedRoles.length / 2));
  }

  const secrets = selected.map((player) => player.characteristics.find((c) => c.type === "secret")).filter(Boolean);
  if (secrets.some((secret) => secret.tags.includes("negative"))) {
    chronicle.push({ time: "Місяць 5", text: "Одна з прихованих таємниць спричинила гострий конфлікт. Довіра в групі різко впала, а частину робіт довелося виконувати під наглядом." });
    score -= 1;
  } else {
    chronicle.push({ time: "Місяць 5", text: "Попри напруження, група виробила зрозумілі правила співжиття, розподілу праці та доступу до запасів." });
  }

  const childfreeStatuses = selected
    .map((player) => player.characteristics.find((c) => c.type === "childfree"))
    .filter(Boolean);
  const childfreeCount = childfreeStatuses.filter((status) => status.tags.includes("childfree")).length;
  const longIsolation = state.game.catastrophe.tags.some((tag) => /(?:8|12) років|невідом/i.test(tag));

  if (longIsolation && selected.length && childfreeCount === selected.length) {
    chronicle.push({
      time: "Місяць 7",
      text: "Усі мешканці виявилися чайлдфрі. Група не стала будувати майбутнє на примусовому батьківстві й зробила ставку на пошук інших громад та об’єднання вцілілих.",
    });
  } else if (longIsolation && childfreeCount > 0) {
    chronicle.push({
      time: "Місяць 7",
      text: "Погляди мешканців на батьківство різнилися. Група окремо закріпила добровільність особистих рішень і зосередилася на виживанні всієї громади.",
    });
  }

  const hasAbsurd = selected.some((player) => player.mode === "chaotic" || player.characteristics.some((characteristic) => characteristic.tags.includes("absurd")));
  if (hasAbsurd) {
    chronicle.push({ time: "Місяць 8", text: "Одна з найбезглуздіших рис мешканців несподівано стала корисною. Офіційний журнал не пояснює, чому після цього біля генератора з’явилася гумова качка." });
    score += 1;
  }

  if (collapsedResources.length || score < 7) {
    chronicle.push({ time: "Місяць 11", text: "Нестача ресурсів, людей і потрібних навичок запустила ланцюг аварій. Сховище більше не могло стабільно підтримувати життя." });
    chronicle.push({ time: "Результат", text: "Група не змогла створити життєздатну громаду." });
  } else if (score >= 15) {
    chronicle.push({ time: "Рік 3", text: "Сховище перетворилося на стійку громаду. Мешканці налагодили ремонт, вирощування їжі та обережний зв’язок із зовнішнім світом." });
    chronicle.push({ time: "Результат", text: "Висока ймовірність довготривалого виживання та відновлення громади." });
  } else {
    chronicle.push({ time: "Рік 2", text: "Група вижила, але втратила значну частину запасів і мусила ризикнути раннім виходом або пошуком інших вцілілих." });
    chronicle.push({ time: "Результат", text: "Виживання можливе, але майбутнє залишається непевним." });
  }

  els.finalChronicle.innerHTML = chronicle.map((entry) => `<article class="chronicle-entry"><strong>${escapeHtml(entry.time)}</strong><p>${escapeHtml(entry.text)}</p></article>`).join("");
  els.finalDialog.showModal();
}

function saveGame() {
  if (!state.game) return;
  try {
    localStorage.setItem(SAVE_KEY, JSON.stringify({
      version: SAVE_VERSION,
      game: state.game,
      selectedPlayerId: state.selectedPlayerId,
    }));
    updateResumeButton();
  } catch (error) {
    console.warn("Не вдалося зберегти партію:", error);
  }
}

function loadSavedGame() {
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (!raw) return null;
    const saved = JSON.parse(raw);
    if (saved.version !== SAVE_VERSION || !saved.game?.players?.length) return null;
    return saved;
  } catch (error) {
    console.warn("Не вдалося прочитати збереження:", error);
    return null;
  }
}

function resumeSavedGame() {
  const saved = loadSavedGame();
  if (!saved) {
    clearSavedGame();
    toast("Збережену партію не знайдено.");
    return;
  }

  state.game = saved.game;
  state.game.eventRounds ||= [];
  state.game.allies ||= [];
  state.game.gameLog ||= [];
  state.game.finalModifiers ||= [];
  state.game.pendingEvent ||= null;
  state.game.eventDecisionMode ||= "vote";
  state.game.discussionDuration ||= 0;
  state.game.discussionRemaining ??= state.game.discussionDuration;
  state.game.phase ||= "reveal";
  state.game.players.forEach((player) => {
    player.roleId ||= null;
    player.roleMastery ||= false;
    player.bonusVote ||= 0;
    if (!player.characteristics.some((item) => item.type === "relationship")) {
      player.characteristics.push(makeCharacteristic("relationship", {
        name: "Стосунок не визначено",
        description: "Цей персонаж не має згенерованого зв’язку у старому збереженні.",
        tags: ["social"],
      }));
    }
  });
  state.selectedPlayerId = saved.selectedPlayerId || state.game.players[0].id;
  state.characterVisible = false;
  state.voting = null;
  state.eventVoting = null;
  stopDiscussionTimer();

  els.setupScreen.classList.remove("active");
  els.gameScreen.classList.add("active");
  els.resetGameButton.classList.remove("hidden");
  renderGame();
  if (state.game.pendingEvent) window.setTimeout(openPendingEvent, 80);
  toast("Партію відновлено.");
}

function clearSavedGame() {
  try {
    localStorage.removeItem(SAVE_KEY);
  } catch (error) {
    console.warn("Не вдалося видалити збереження:", error);
  }
  updateResumeButton();
}

function updateResumeButton() {
  if (!els.resumeGameButton) return;
  els.resumeGameButton.classList.toggle("hidden", !loadSavedGame());
}

