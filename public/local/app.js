function confirmAbility(event) {
  event.preventDefault();
  const player = selectedPlayer();
  if (!player || player.ability.used) return;

  const target = state.game.players.find((p) => p.id === els.abilityTarget.value);
  let message = "Здібність використано.";

  switch (player.ability.effect) {
    case "inspect_health": {
      const health = target?.characteristics.find((c) => c.type === "health");
      message = target && health ? `${target.name}: ${health.name}.` : "Не вдалося застосувати здібність.";
      break;
    }
    case "inspect_secret": {
      const secret = target?.characteristics.find((c) => c.type === "secret");
      message = target && secret ? `${target.name}: ${secret.name}.` : "Не вдалося застосувати здібність.";
      break;
    }
    case "force_reveal": {
      if (target) {
        const hidden = target.characteristics.filter((c) => !c.revealed);
        if (hidden.length) {
          const chosen = randomItem(hidden);
          revealCharacteristic(target.id, chosen.id, true);
          message = `${target.name} змушений відкрити: ${TYPE_LABELS[chosen.type]} — ${chosen.name}.`;
        } else {
          message = "У цілі вже немає прихованих характеристик.";
        }
      }
      break;
    }
    case "hide_own": {
      const revealed = player.characteristics.filter((c) => c.revealed);
      if (revealed.length) {
        const chosen = randomItem(revealed);
        chosen.revealed = false;
        message = `Приховано характеристику: ${TYPE_LABELS[chosen.type]}.`;
      } else {
        message = "У вас немає відкритих характеристик.";
      }
      break;
    }
    case "extra_reveal": {
      const hidden = player.characteristics.filter((c) => !c.revealed);
      if (hidden.length) {
        const chosen = randomItem(hidden);
        revealCharacteristic(player.id, chosen.id, true);
        message = `Додатково відкрито: ${TYPE_LABELS[chosen.type]} — ${chosen.name}.`;
      } else {
        message = "У вас уже все відкрито.";
      }
      break;
    }
    case "reveal_relationship": {
      const relationship = target?.characteristics.find((c) => c.type === "relationship");
      if (target && relationship && !relationship.revealed) {
        revealCharacteristic(target.id, relationship.id, true);
        message = `${target.name} відкриває стосунок: ${relationship.name}.`;
      } else {
        message = "Стосунок цілі вже відкрито або недоступний.";
      }
      break;
    }
    case "double_vote":
      player.bonusVote = 1;
      message = "Наступний голос під час вигнання рахуватиметься за два.";
      break;
    case "resource_cache": {
      const details = applyResourceChanges({ food: 6, water: 6 });
      message = `Запас передано до сховища: ${details.join(", ")}.`;
      break;
    }
    case "role_mastery":
      player.roleMastery = true;
      message = player.roleId
        ? "Внесок обраної ролі посилено до кінця партії."
        : "Майстерність активовано. Вона почне діяти після призначення ролі.";
      break;
    case "protect":
      player.protected = true;
      message = "Захист активовано. Наступне вигнання буде скасовано.";
      break;
  }

  player.ability.used = true;
  logGame("ability", `${player.name} використав здібність «${player.ability.name}».`);
  els.abilityDialog.close();
  renderGame();
  saveGame();
  window.setTimeout(() => alert(message), 50);
}

