function submitEventVote() {
  const voting = state.eventVoting;
  if (!voting?.selectedChoiceId) return;
  voting.votes[voting.selectedChoiceId] = (voting.votes[voting.selectedChoiceId] || 0) + 1;
  voting.currentVoterIndex += 1;

  if (voting.currentVoterIndex < voting.voterIds.length) {
    renderEventVotingStep();
    return;
  }

  const event = EVENTS.find((item) => item.id === voting.eventId);
  const sorted = Object.entries(voting.votes).sort((a, b) => b[1] - a[1]);
  const maxVotes = sorted[0]?.[1] || 0;
  const tied = sorted.filter(([, count]) => count === maxVotes).map(([choiceId]) => choiceId);
  const winnerChoiceId = randomItem(tied);
  const summary = event.choices
    .map((choice) => `${choice.label} — ${voting.votes[choice.id] || 0}`)
    .join("; ");

  state.eventVoting = null;
  els.eventVotingDialog.close();
  resolveEventChoice(event.id, winnerChoiceId, summary);
}

function cancelEventVoting() {
  state.eventVoting = null;
  if (els.eventVotingDialog.open) els.eventVotingDialog.close();
  if (state.game?.pendingEvent) {
    const event = EVENTS.find((item) => item.id === state.game.pendingEvent.eventId);
    if (event) renderEventDialog(event);
  }
}

function resolveEventChoice(eventId, choiceId, voteSummary = null) {
  const pending = state.game.pendingEvent;
  if (!pending || pending.resolved || pending.eventId !== eventId) return;
  const event = EVENTS.find((item) => item.id === eventId);
  const choice = event?.choices.find((item) => item.id === choiceId);
  if (!event || !choice) return;

  const chance = calculateChoiceChance(choice);
  const success = choice.automatic || Math.random() <= chance;
  const pool = success || !choice.failureOutcomes.length ? choice.successOutcomes : choice.failureOutcomes;
  const outcome = clone(randomItem(pool));
  const details = applyResourceChanges(outcome.resources || {});

  (outcome.modifiers || []).forEach((modifier) => {
    if (!state.game.finalModifiers.includes(modifier)) state.game.finalModifiers.push(modifier);
  });

  if (outcome.ally) {
    state.game.allies ||= [];
    state.game.allies.push(outcome.ally);
    details.push(`Новий союзник: ${outcome.ally.name}`);
  }

  pending.resolved = true;
  pending.choiceId = choiceId;
  pending.voteSummary = voteSummary;
  pending.outcome = { text: outcome.text, details, success };
  logGame("event", `Рішення: «${choice.label}». ${outcome.text}`);
  renderGame();
  renderEventDialog(event);
  saveGame();
}

