calculateTagPower = function calculateTagPowerV05(tags) {
  if (!tags.length) return 0;
  let total = 0;
  const weights = { origin: 0.35, profession: 1.15, skill: 1.35, item: 0.7, hobby: 0.55, trait: 0.45, health: 0.3, secret: 0.25, phobia: 0.15, relationship: 0.25 };
  activePlayers().forEach((player) => {
    let playerPower = 0;
    player.characteristics.forEach((characteristic) => {
      const matches = characteristic.tags.filter((tag) => tags.includes(tag)).length;
      if (matches) playerPower += (weights[characteristic.type] || 0.25) * matches;
    });
    const role = getPlayerRole(player);
    if (role) playerPower += role.tags.filter((tag) => tags.includes(tag)).length * (player.roleMastery ? 1.25 : 0.75);
    playerPower *= v05ConditionInfo(player).factor;
    total += Math.min(playerPower, player.roleMastery ? 3.2 : 2.7);
  });
  (state.game.allies || []).forEach((ally) => { total += (ally.tags || []).filter((tag) => tags.includes(tag)).length * 0.8; });
  return Math.min(total, 7);
};

