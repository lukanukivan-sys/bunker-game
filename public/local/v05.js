function v05LaunchExpedition(event) {
  event.preventDefault();
  const { location, players } = v05SelectedExpeditionData();
  if (!location || players.length < 1 || players.length > 2) return toast("Оберіть маршрут і від одного до двох учасників.");
  const chance = v05ExpeditionChance(location, players);
  const success = Math.random() < chance;
  state.game.expeditionRounds ||= [];
  state.game.expeditionHistory ||= [];
  state.game.expeditionRounds.push(state.game.round);

  const changes = success ? location.success : location.failure;
  const details = applyResourceChanges(changes);
  players.forEach((player) => {
    player.stress = clamp((player.stress || 0) + (success ? randomInt(3, 9) : randomInt(12, 24)), 0, 100);
    if (success) player.successfulExpeditions = (player.successfulExpeditions || 0) + 1;
    else player.failedExpeditions = (player.failedExpeditions || 0) + 1;
  });

  let text;
  if (success) {
    text = `Експедиція до «${location.name}» завершилася успішно. Зміни: ${details.join(", ")}.`;
    if (location.asset && Math.random() < 0.42) {
      state.game.allies.push(clone(location.asset));
      text += ` Знайдено: ${location.asset.name}.`;
    }
  } else {
    const injured = randomItem(players);
    v05ApplySetback(injured, location.difficulty >= 5 || Math.random() < 0.25, `Травма під час експедиції до «${location.name}»`);
    text = `Експедиція до «${location.name}» провалилася. Зміни: ${details.join(", ")}.`;
  }

  state.game.expeditionHistory.push({ round: state.game.round, locationId: location.id, playerIds: players.map((p) => p.id), success });
  logGame("expedition", text);
  v05Els.expeditionDialog.close();
  renderGame();
  saveGame();
  toast(success ? "Експедиція повернулася з результатом." : "Експедиція зазнала невдачі.");
}

