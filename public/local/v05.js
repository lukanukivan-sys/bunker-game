function v05ConditionInfo(player) {
  const injuries = player.injuries || [];
  const stress = player.stress || 0;
  if (injuries.length >= 2) return { id: "critical", name: "Важкий стан", description: `${injuries.join("; ")}. Потрібен медичний нагляд.`, factor: 0.55 };
  if (injuries.length === 1) return { id: "injured", name: "Травмований", description: injuries[0], factor: 0.76 };
  if (stress >= 55) return { id: "stressed", name: "Виснажений стресом", description: `Рівень стресу: ${stress}%.`, factor: 0.84 };
  return { id: "stable", name: "Стабільний стан", description: stress ? `Незначний стрес: ${stress}%.` : "Травм і вираженого виснаження немає.", factor: 1 };
}

function v05ApplySetback(player, severe = false, reason = "Невідома травма") {
  if (!player) return;
  player.injuries ||= [];
  player.stress ||= 0;
  if (severe || Math.random() < 0.45) {
    if (!player.injuries.includes(reason)) player.injuries.push(reason);
    logGame("condition", `${player.name} отримує травму: ${reason}.`);
  } else {
    const increase = randomInt(16, 30);
    player.stress = clamp(player.stress + increase, 0, 100);
    logGame("condition", `${player.name}: рівень стресу зріс на ${increase}%.`);
  }
}

function v05AttachGoals(players, shelter) {
  players.forEach((player) => {
    const candidates = V05_GOAL_TEMPLATES.filter((template) => {
      if (["protect", "outlast"].includes(template.type)) return players.length > 1;
      if (template.type === "module") return shelter.modules?.length;
      return true;
    });
    const template = randomItem(candidates);
    const ctx = {};
    if (["protect", "outlast"].includes(template.type)) ctx.target = randomItem(players.filter((other) => other.id !== player.id));
    if (template.type === "resource") {
      ctx.resource = randomItem(Object.keys(RESOURCE_LABELS));
      ctx.threshold = randomItem([38, 45, 52]);
    }
    if (template.type === "module") {
      ctx.module = randomItem(shelter.modules);
      ctx.threshold = randomItem([45, 55, 65]);
    }
    player.goal = {
      type: template.type,
      name: template.name,
      description: template.description(ctx),
      targetId: ctx.target?.id || null,
      resource: ctx.resource || null,
      moduleId: ctx.module?.id || null,
      threshold: ctx.threshold || null,
    };
  });
}

function v05EvaluateGoal(player) {
  const goal = player.goal;
  if (!goal) return { success: false, text: "Особисту мету не визначено." };
  let success = false;
  switch (goal.type) {
    case "survive": success = player.active; break;
    case "protect": success = Boolean(state.game.players.find((p) => p.id === goal.targetId)?.active); break;
    case "outlast": success = player.active && !state.game.players.find((p) => p.id === goal.targetId)?.active; break;
    case "resource": success = (state.game.shelter.resources[goal.resource] || 0) >= goal.threshold; break;
    case "module": success = (state.game.shelter.modules.find((m) => m.id === goal.moduleId)?.condition || 0) >= goal.threshold; break;
    case "reveal": success = player.characteristics.filter((c) => c.revealed).length >= 4; break;
    case "ability": success = Boolean(player.ability.used); break;
    case "role": success = player.active && Boolean(player.roleId); break;
    case "explorer": success = (player.successfulExpeditions || 0) >= 1; break;
    case "repair": success = (player.workSuccesses || 0) >= 1; break;
  }
  return { success, text: success ? "Мету виконано." : "Мету не виконано." };
}

