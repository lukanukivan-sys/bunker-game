function v05ActionPower(players, tags) {
  return players.reduce((total, player) => {
    let value = 0;
    player.characteristics.forEach((characteristic) => {
      const matches = characteristic.tags.filter((tag) => tags.includes(tag)).length;
      const weight = characteristic.type === "profession" ? 1.5 : characteristic.type === "skill" ? 1.7 : characteristic.type === "item" ? 0.8 : 0.4;
      value += matches * weight;
    });
    const role = getPlayerRole(player);
    if (role) value += role.tags.filter((tag) => tags.includes(tag)).length * 0.8;
    return total + value * v05ConditionInfo(player).factor;
  }, 0);
}

function v05ExpeditionChance(location, players) {
  if (!location || !players.length) return 0;
  const power = v05ActionPower(players, location.tags);
  const teamBonus = players.length === 2 ? 0.08 : 0;
  return clamp(0.35 + power * 0.065 + teamBonus - location.difficulty * 0.055, 0.12, 0.9);
}

