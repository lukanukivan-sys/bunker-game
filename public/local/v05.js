pickCatastrophe = function pickCatastropheV05(absurdityLevel, settingId = "modern") {
  const options = v05Pack(settingId).catastrophes;
  const absurdChance = [0, 0.02, 0.05, 0.14, 0.35][absurdityLevel];
  const absurdOptions = options.filter((c) => c.absurdity);
  const normalOptions = options.filter((c) => !c.absurdity);
  const pool = Math.random() < absurdChance && absurdOptions.length ? absurdOptions : normalOptions;
  return clone(randomItem(pool.length ? pool : options));
};

generateShelter = function generateShelterV05(capacity, settingId = "modern") {
  const pack = v05Pack(settingId);
  const base = clone(randomItem(pack.shelters));
  base.capacity = capacity;
  base.quirk = randomItem(pack.quirks);
  base.resources = Object.fromEntries(
    Object.entries(base.baseResources).map(([key, value]) => [key, clamp(value + randomInt(-7, 7), 25, 100)]),
  );
  base.modules = pack.modules.map(([id, name, description, tags]) => ({
    id,
    name,
    description,
    tags,
    condition: clamp(randomInt(52, 96), 0, 100),
  }));
  return base;
};

generatePlayers = function generatePlayersV05(names, absurdityLevel, uniqueProfessions, minimizeRepeats, settingId = "modern") {
  const used = {
    professions: new Set(), health: new Set(), skills: new Set(), traits: new Set(), items: new Set(),
    secrets: new Set(), hobbies: new Set(), phobias: new Set(), abilities: new Set(), origins: new Set(),
  };

  return names.map((name, index) => {
    const mode = chooseMode(absurdityLevel);
    const profession = chooseEntry(v05Pool("professions", settingId), mode, uniqueProfessions || minimizeRepeats ? used.professions : new Set());
    if (uniqueProfessions || minimizeRepeats) used.professions.add(profession.id);

    const originPool = (V05_ORIGINS[settingId] || V05_ORIGINS.modern).filter((item) => !used.origins.has(item.id));
    const origin = chooseEntry(originPool.length ? originPool : V05_ORIGINS[settingId], mode);
    if (minimizeRepeats) used.origins.add(origin.id);
    const ageValue = randomInt(origin.ageMin || 18, origin.ageMax || 78);

    let sex = chooseEntry(CONTENT.sex, "coherent");
    let childfree = chooseEntry(CONTENT.childfree, "coherent");
    if (origin.id === "synthetic") {
      sex = { id: "synthetic_sex", name: "Не застосовується", description: "Штучне тіло не має біологічної статі.", tags: ["synthetic"] };
      childfree = { id: "synthetic_childfree", name: "Не застосовується", description: "Поняття біологічного батьківства до цього тіла не застосовується.", tags: ["synthetic"] };
    }

    const healthPool = v05Pool("health", settingId).filter((item) => item.id !== "pregnant" || (sex.id === "female" && ageValue <= 50));
    const health = chooseContextualEntry(healthPool, mode, profession, minimizeRepeats ? used.health : new Set());
    const skill = chooseContextualEntry(v05Pool("skills", settingId), mode, profession, minimizeRepeats ? used.skills : new Set());
    const trait = chooseContextualEntry(CONTENT.traits, mode, profession, minimizeRepeats ? used.traits : new Set());
    const hobby = chooseContextualEntry(CONTENT.hobbies, mode, profession, minimizeRepeats ? used.hobbies : new Set());
    const phobia = chooseContextualEntry(CONTENT.phobias, mode, profession, minimizeRepeats ? used.phobias : new Set());
    const item = chooseContextualEntry(v05Pool("items", settingId), mode, profession, minimizeRepeats ? used.items : new Set());
    const secret = chooseContextualEntry(v05Pool("secrets", settingId), mode, profession, minimizeRepeats ? used.secrets : new Set());
    const chosenAbility = chooseEntry(CONTENT.abilities, mode, minimizeRepeats ? used.abilities : new Set());

    if (minimizeRepeats) {
      used.health.add(health.id); used.skills.add(skill.id); used.traits.add(trait.id); used.hobbies.add(hobby.id);
      used.phobias.add(phobia.id); used.items.add(item.id); used.secrets.add(secret.id); used.abilities.add(chosenAbility.id);
    }

    return {
      id: `player-${index + 1}-${Date.now()}-${cryptoRandomId()}`,
      name,
      mode,
      characteristics: [
        makeCharacteristic("origin", origin),
        makeCharacteristic("profession", profession),
        makeCharacteristic("age", { name: `${ageValue} років`, description: ageDescription(ageValue), tags: [ageValue < 25 ? "young" : ageValue > 60 ? "old" : "adult"] }),
        makeCharacteristic("sex", sex),
        makeCharacteristic("childfree", childfree),
        makeCharacteristic("hobby", hobby),
        makeCharacteristic("phobia", phobia),
        makeCharacteristic("health", health),
        makeCharacteristic("skill", skill),
        makeCharacteristic("trait", trait),
        makeCharacteristic("item", item),
        makeCharacteristic("secret", secret),
      ],
      ability: { ...clone(chosenAbility), used: false },
      active: true,
      protected: false,
      bonusVote: 0,
      roleId: null,
      roleMastery: false,
      revealedThisRound: 0,
      stress: 0,
      injuries: [],
      successfulExpeditions: 0,
      failedExpeditions: 0,
      workSuccesses: 0,
    };
  });
};

startGame = function startGameV05(event) {
  event.preventDefault();
  const names = parsePlayerNames();
  if (names.length < 4) return toast("Потрібно щонайменше 4 гравці.");
  const capacity = Number(els.shelterCapacity.value);
  if (capacity >= names.length) return toast("Місць у сховищі має бути менше, ніж гравців.");

  const settingId = els.settingSelect.value || "modern";
  const absurdityLevel = Number(els.absurdityLevel.value);
  const catastrophe = pickCatastrophe(absurdityLevel, settingId);
  const shelter = generateShelter(capacity, settingId);
  const players = generatePlayers(names, absurdityLevel, els.uniqueProfessions.checked, els.minimizeRepeats.checked, settingId);
  attachRelationships(players, absurdityLevel);
  v05AttachGoals(players, shelter);

  state.game = {
    players,
    activePlayerIds: players.map((p) => p.id),
    catastrophe,
    shelter,
    settingId,
    capacity,
    round: 1,
    maxRounds: Number(els.roundCount.value),
    phase: "reveal",
    events: [],
    votesHistory: [],
    finalModifiers: [],
    eventRounds: [],
    expeditionRounds: [],
    workRounds: [],
    expeditionHistory: [],
    allies: [],
    gameLog: [],
    pendingEvent: null,
    eventDecisionMode: els.eventDecisionMode.value,
    discussionDuration: Number(els.discussionMinutes.value) * 60,
    discussionRemaining: Number(els.discussionMinutes.value) * 60,
    roles: {},
  };

  state.selectedPlayerId = players[0].id;
  state.characterVisible = false;
  state.currentEventIndex = -1;
  els.setupScreen.classList.remove("active");
  els.gameScreen.classList.add("active");
  els.resetGameButton.classList.remove("hidden");

  logGame("system", `Партію створено в сетингу «${V05_SETTING_META[settingId].name}». Катастрофа: ${catastrophe.title}. Місць: ${capacity}.`);
  renderGame();
  saveGame();
  toast("Партію створено.");
};

